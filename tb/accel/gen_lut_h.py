#!/usr/bin/env python3
"""Generate sw/common/accel_exp_lut.h from p1's model/exp_lut.hex (the table the
RTL and attn_fixed use).   python3 tb/accel/gen_lut_h.py [P1_ROOT] [OUT]
With --check, exit 1 when OUT differs from what would be generated."""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
P2 = HERE.parents[1]
DEFAULT_P1 = pathlib.Path("/home/saad/p1-attention")
DEFAULT_OUT = P2 / "sw/common/accel_exp_lut.h"


def render(hex_path):
    vals = [int(t, 16) for t in hex_path.read_text().split()]
    assert len(vals) == 1024 and vals[0] == 0x8000, "unexpected exp LUT"
    lines = ["// exp() LUT, UQ1.15, 1024 entries: lut[j] = round(2^15 exp(-j/64)).",
             "// GENERATED by tb/accel/gen_lut_h.py from p1-attention model/exp_lut.hex.",
             "// Do not edit.",
             "#ifndef ACCEL_EXP_LUT_H", "#define ACCEL_EXP_LUT_H", "#include <stdint.h>",
             "static const uint16_t accel_exp_lut[1024] = {"]
    for i in range(0, 1024, 8):
        lines.append("    " + ", ".join(f"0x{v:04x}" for v in vals[i:i + 8]) + ",")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    p1 = pathlib.Path(args[0]) if args else DEFAULT_P1
    out = pathlib.Path(args[1]) if len(args) > 1 else DEFAULT_OUT
    text = render(p1 / "model/exp_lut.hex")
    if "--check" in sys.argv:
        ok = out.exists() and out.read_text() == text
        print(f"{out}: {'up to date' if ok else 'STALE'}")
        sys.exit(0 if ok else 1)
    out.write_text(text)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
