"""Behavioral Verilog models for the sky130 cells a netlist uses, built from
the Liberty file: combinational cells from their `function` attribute,
flip-flops from their `ff` group. Fault simulates the netlist with these.

usage: python3 gen_cells.py <liberty> <netlist.v> <out.v>
"""
import re
import sys


def lib_cells(text):
    """Yield (name, body) for every cell group in a Liberty file."""
    for m in re.finditer(r'\bcell\s*\(\s*"?([\w$]+)"?\s*\)\s*\{', text):
        depth, i = 1, m.end()
        while depth:
            c = text[i]
            depth += (c == "{") - (c == "}")
            i += 1
        yield m.group(1), text[m.end():i - 1]


def groups(body, kind):
    """Yield (arg, inner) for each `kind (arg) { ... }` group at any depth."""
    for m in re.finditer(r'\b%s\s*\(([^)]*)\)\s*\{' % kind, body):
        depth, i = 1, m.end()
        while depth:
            c = body[i]
            depth += (c == "{") - (c == "}")
            i += 1
        yield m.group(1).replace('"', "").strip(), body[m.end():i - 1]


def attr(body, name):
    m = re.search(r'\b%s\s*:\s*"?([^";\n]*)"?\s*;' % name, body)
    return m.group(1).strip() if m else None


def vexpr(f):
    """Liberty boolean function -> Verilog expression."""
    f = f.replace("*", "&").replace("+", "|")
    f = re.sub(r"(\w+|\))\s*'", r"(!\1)", f)       # postfix complement
    f = re.sub(r"(\w|\))\s+(?=[\w(!])", r"\1 & ", f)  # juxtaposition is AND
    return f


def model(name, body):
    if list(groups(body, "latch")) or list(groups(body, "statetable")):
        raise ValueError(f"{name}: latch/statetable cell not modeled")
    pins = {}
    for pname, pbody in groups(body, "pin"):
        pins[pname.strip()] = (attr(pbody, "direction"), attr(pbody, "function"))
    ins = [p for p, (d, _) in pins.items() if d == "input"]
    outs = [p for p, (d, _) in pins.items() if d == "output"]
    ports = ", ".join(outs + ins)
    lines = [f"module {name} ({ports});"]
    lines += [f"  input {p};" for p in ins] + [f"  output {p};" for p in outs]
    ff = list(groups(body, "ff"))
    if ff:
        names = [n.strip() for n in ff[0][0].split(",")]
        iq = names[0]
        fb = ff[0][1]
        clk, nxt = attr(fb, "clocked_on"), attr(fb, "next_state")
        clr, pre = attr(fb, "clear"), attr(fb, "preset")
        edge = f"negedge {clk[1:]}" if clk.startswith("!") else f"posedge {clk}"
        lines.append(f"  reg {iq};")
        if len(names) > 1:
            lines.append(f"  wire {names[1]} = !{iq};")
        sens, body_v = [edge], f"{iq} <= {vexpr(nxt)};"
        if pre:
            p = pre[1:] if pre.startswith("!") else pre
            sens.append(("negedge " if pre.startswith("!") else "posedge ") + p)
            body_v = f"if ({vexpr(pre)}) {iq} <= 1'b1; else " + body_v
        if clr:
            c = clr[1:] if clr.startswith("!") else clr
            sens.append(("negedge " if clr.startswith("!") else "posedge ") + c)
            body_v = f"if ({vexpr(clr)}) {iq} <= 1'b0; else " + body_v
        lines.append(f"  initial {iq} = 1'b0;")
        lines.append(f"  always @({' or '.join(sens)}) {body_v}")
    for o in outs:
        fn = pins[o][1]
        if fn is None:
            raise ValueError(f"{name}.{o}: no function")
        lines.append(f"  assign {o} = {vexpr(fn)};")
    lines.append("endmodule\n")
    return "\n".join(lines)


def main():
    """Models every cell the netlist uses (an error if one cannot be modeled)
    plus every other liberty cell that can be, since fault chain resynthesizes
    with cells of its own choosing."""
    lib, netlist, out = sys.argv[1:4]
    text = open(lib).read()
    used = set(re.findall(r"^\s*(sky130_fd_sc_hd__\w+)\s", open(netlist).read(), re.M))
    cells = dict(lib_cells(text))
    missing = used - cells.keys()
    if missing:
        sys.exit(f"cells not in liberty: {sorted(missing)}")
    n = 0
    with open(out, "w") as fo:
        fo.write("// generated by dft/gen_cells.py from " + lib.split("/")[-1] + "\n")
        for c in sorted(cells):
            try:
                text_v = model(c, cells[c])
            except (ValueError, AttributeError, TypeError):
                if c in used:
                    raise
                continue  # latches, tap/fill/diode cells and the like
            fo.write(text_v)
            n += 1
    print(f"{n} cell models ({len(used)} used by the netlist) -> {out}")


if __name__ == "__main__":
    main()
